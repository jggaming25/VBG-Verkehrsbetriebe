export function t(cfg, key, vars = {}) {
  const lang = cfg && cfg.language === 'en' ? 'en' : 'de';
  let m = MESSAGES[lang][key] ?? MESSAGES.de[key] ?? key;
  if (typeof m === 'function') m = m(...Object.values(vars));
  for (const [k, v] of Object.entries(vars)) {
    m = String(m).replaceAll(`{${k}}`, String(v));
  }
  return m;
}